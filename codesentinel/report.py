"""Render a compiled review into Markdown (used for files, PR comments and the UI)."""

from __future__ import annotations

from codesentinel.models import AGENT_TITLES

VERDICT_TEXT = {
    "block": "Blocked: critical issues must be fixed",
    "request_changes": "Changes requested",
    "approve_with_comments": "Approved with comments",
    "approve": "Approved",
}
SEV_BADGE = {"critical": "🔴 Critical", "high": "🟠 High", "medium": "🟡 Medium", "low": "🔵 Low", "info": "⚪ Info"}


def to_markdown(report: dict, include_tests: bool = True) -> str:
    src = report.get("source", {})
    counts = report["counts"]
    lines = [
        "# CodeSentinel review report",
        "",
        f"**Source:** {src.get('label', 'pasted code')}  ",
        f"**Project:** `{report['namespace']}`  ",
        f"**Generated:** {report['generated_at']}  ",
        f"**Verdict:** {VERDICT_TEXT[report['verdict']]}  ",
        f"**Quality score:** {report['score']} / 100"
        + (f" (previous review: {report['previous_score']})" if report.get("previous_score") is not None else ""),
        "",
        "## Summary",
        "",
        report["summary"],
        "",
        "| Critical | High | Medium | Low | Info |",
        "|---:|---:|---:|---:|---:|",
        f"| {counts['critical']} | {counts['high']} | {counts['medium']} | {counts['low']} | {counts['info']} |",
        "",
    ]
    if report.get("escalations"):
        lines += ["## Escalations", ""] + [f"- ⚠️ {e}" for e in report["escalations"]] + [""]

    lines += ["## Findings (highest priority first)", ""]
    if not report["findings"]:
        lines.append("No findings.")
    for i, f in enumerate(report["findings"], 1):
        cwe = f" · {f['cwe']}" if f.get("cwe") else ""
        lines += [
            f"### {i}. {SEV_BADGE[f['severity']]} · {f['title']}",
            "",
            f"`{f['file']}:{f['line']}` · {AGENT_TITLES[f['agent']]} · rule {f['rule_id']}{cwe} · "
            f"source {f['source']} · confidence {f['confidence']:.2f}",
            "",
        ]
        if f.get("evidence"):
            lines += ["```", f["evidence"], "```", ""]
        lines += [f"**Why it matters:** {f['explanation']}", "", f"**Fix:** {f['recommendation']}", ""]
        if include_tests and f.get("suggested_test"):
            lines += ["<details><summary>Suggested test</summary>", "", "```python", f["suggested_test"], "```",
                      "", "</details>", ""]

    if report.get("suppressed"):
        lines += ["## Suppressed by team memory", ""]
        lines += [f"- `{s['file']}:{s['line']}` {s['title']} ({s['rule_id']}): {s['suppressed_reason']}"
                  for s in report["suppressed"]] + [""]

    lines += ["## Agent runs", "", "| Agent | Mode | Model | Status | Tool calls | Cache | Seconds |",
              "|---|---|---|---|---:|---|---:|"]
    for r in report.get("agent_runs", []):
        lines.append(f"| {AGENT_TITLES[r['agent']]} | {r['mode']} | {r.get('model') or 'none'} | {r['status']} | "
                     f"{r.get('tool_calls', 0)} | {r.get('cache', 'miss')} | {r.get('duration_s', 0)} |")
    approver = report.get("approved_by")
    if approver == "auto":
        footer = "Generated in read only automatic mode. No human has reviewed this report yet."
    elif approver:
        footer = f"Reviewed and approved by {approver} before it was shared."
    else:
        footer = "Draft awaiting human review."
    lines += ["", f"_Generated by CodeSentinel, a LangGraph multi agent code reviewer. {footer}_"]
    return "\n".join(lines)
